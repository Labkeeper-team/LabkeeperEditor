function program(): Program {
    return {
        segments: [
            {
                id: 1,
                type: 'md',
                parameters: { visible: true },
                text: 'see notes.txt and img/a.png',
            },
        ],
        parameters: { roundStrategy: 'threeDigits' },
    };
}

const ok = <T>(body: T) => ({
    code: 200,
    isOk: true,
    isUnauth: false,
    isForbidden: false,
    body,
});

function readText(blob: Blob): Promise<string> {
    return new Promise((resolve) => {
        const reader = new FileReader();
        reader.onload = () => resolve(String(reader.result));
        reader.readAsText(blob);
    });
}

/** CollabSocket over the test network; drop/reconnect simulate a lost connection */
function testSocket(
    net: TestNetwork,
    user: { userId: number; displayName: string; color: string }
): CollabSocket & { drop: () => void; reconnect: () => void } {
    let counter = 0;
    let connectionId = '';
    let handlers: Parameters<CollabSocket['connect']>[1] | null = null;
    const open = () => {
        counter += 1;
        connectionId = `${user.displayName}-${counter}`;
        handlers!.onOpen();
        net.open(
            connectionId,
            user,
            (frame) => handlers?.onFrame(frame),
            (code) =>
                handlers?.onClose(
                    code === 1008 ? 'denied' : 'closed',
                    code !== 1008
                )
        );
    };
    return {
        connect: (_projectId, h): CollabConnection => {
            handlers = h;
            open();
            return {
                send: (frame) => net.send(connectionId, frame),
                isOpen: () => net.isOpen(connectionId),
                close: () => net.close(connectionId),
            };
        },
        drop: () => {
            net.close(connectionId);
            handlers?.onClose('closed', true);
        },
        reconnect: () => open(),
    };
}

function makeUser(
    net: TestNetwork,
    user: { userId: number; displayName: string; color: string }
) {
    const mvs: MockViewModelRepository = mockViewModelState();
    const rpi: Rpi = mockRpi();
    rpi.getProjectRequest = jest
        .fn()
        .mockResolvedValue(ok({ program: program() }));
    rpi.saveProgramRequest = jest.fn().mockResolvedValue(ok({}));
    // REST knows the generated files; user files of the session are newer
    rpi.listFilesRequest = jest
        .fn()
        .mockResolvedValue(ok({ files: [GENERATED] }));
    rpi.uploadFileRequest = jest.fn().mockResolvedValue(ok('url'));
    rpi.renameFileRequest = jest.fn().mockResolvedValue(ok({}));
    rpi.deleteFileRequest = jest.fn().mockResolvedValue(ok({}));
    rpi.uploadCollabFileRequest = jest
        .fn()
        .mockImplementation(
            async (
                formData: FormData,
                _projectId: string,
                name: string,
                connectionId: string
            ) => {
                const content = await readText(formData.get('file') as Blob);
                const code = net.authority.upload(
                    connectionId,
                    name.replace(/^\//, ''),
                    content
                );
                return {
                    code,
                    isOk: code === 201,
                    isUnauth: false,
                    isForbidden: code === 403,
                    body: 'url',
                };
            }
        );
    const socket = testSocket(net, user);
    const collabRepository = inMemoryCollabRepository();
    const ctx = setupContext(
        rpi,
        mvs,
        mockObserver(),
        mockAgentSocket().socket,
        {
            socket,
            repository: collabRepository,
        }
    );
    mvs.userViewModelRepository.setUserInfo({
        isAuthenticated: true,
        email: `${user.displayName}@example.com`,
        id: user.userId,
        privacyPolicyAccepted: true,
        crossBorderDataTransferPolicyAccepted: true,
        tokenBalance: 0,
    });
    mvs.projectViewModelRepository.setProject({
        projectId: PROJECT_ID,
        userId: OWNER_ID,
        title: 't',
        lastModified: '',
        program: program(),
        isPublic: true,
        projectType: 'markdown',
    });
    mvs.projectViewModelRepository.setReadOnly(user.userId !== OWNER_ID);
    mvs.projectViewModelRepository.setFiles([GENERATED]);
    ctx.programService.setNewProgram(program());
    mvs.projectViewModelRepository.setCurrentProgram(program());
    return {
        ctx,
        mvs,
        rpi,
        socket,
        collabRepository,
        files: ctx.collabService!.files,
    };
}

type User = ReturnType<typeof makeUser>;

jest.setTimeout(30_000);

/** Runs an operation that waits for server answers while the network delivers them */
async function run<T>(
    net: TestNetwork,
    operation: () => Promise<T>
): Promise<T> {
    const result = operation();
    await settle(net);
    return result;
}

/** Delivers frames and lets awaiting services continue, until nothing moves */
async function settle(net: TestNetwork): Promise<void> {
    for (let round = 0; round < 20; round++) {
        net.flush();
        await new Promise((resolve) => setTimeout(resolve, 0));
    }
    net.flush();
}

function setup(options: Partial<FakeCollabAuthorityOptions> = {}, seed = 7) {
    const authority = new FakeCollabAuthority({
        segments: [{ type: 'md', text: 'see notes.txt and img/a.png' }],
        files: [
            { path: 'notes.txt', content: 'hello\nworld' },
            { path: 'img/a.png', content: 'PNG-1' },
        ],
        folders: ['empty'],
        ...options,
    });
    const net = new TestNetwork(authority, seededRandom(seed));
    const owner = makeUser(net, {
        userId: OWNER_ID,
        displayName: 'alice',
        color: '#e8590c',
    });
    const guest = makeUser(net, {
        userId: GUEST_ID,
        displayName: 'bob',
        color: '#1971c2',
    });
    owner.ctx.collabService!.start(PROJECT_ID);
    guest.ctx.collabService!.start(PROJECT_ID);
    net.flush();
    return { authority, net, owner, guest };
}

const fileNames = (user: User) =>
    user.mvs
        .mockState()
        .files.map((file: LabkeeperFile) => file.fileName)
        .sort();

/** The text file editor view of a user: a Text like CodeMirror keeps, bound like the plugin */
function textEditorView(user: User) {
    const view = {
        doc: Text.of(
            user.mvs.ideViewModelRepository.textFileContent().split('\n')
        ),
        cursors: [] as RemoteCursor[],
        selection: null as { anchor: number; head: number } | null,
    };
    const sink: CollabViewSink = {
        key: () => user.files.bindingKey() ?? '',
        applyRemote: (change, cursors) => {
            view.doc = view.doc.eq(change.before)
                ? change.changes.apply(view.doc)
                : change.after;
            view.cursors = cursors;
        },
        setCursors: (cursors, doc) => {
            if (view.doc.eq(doc)) {
                view.cursors = cursors;
            }
        },
        selection: () => view.selection,
    };
    user.files.binding.attachView(sink);
    return {
        view,
        type: (pos: number, text: string) => {
            const key = user.files.bindingKey()!;
            const changes = ChangeSet.of(
                { from: pos, insert: text },
                view.doc.length
            );
            const start = view.doc;
            view.doc = changes.apply(view.doc);
            user.files.binding.forwardViewChanges(key, 0, changes, start);
            user.ctx.textFileEditorService.onTextFileContentChanged(
                view.doc.toString()
            );
        },
        select: (anchor: number) => {
            view.selection = { anchor, head: anchor };
            user.files.binding.reportSelection(
                user.files.bindingKey()!,
                view.selection
            );
        },
    };
}

async function openTextFile(user: User, net: TestNetwork, path: string) {
    const opened = user.ctx.textFileEditorService.onTextFileOpened(path);
    await settle(net);
    await opened;
}

describe('collaborative project files', () => {
    test('the file list of the session replaces user files and keeps generated ones', () => {
        const { owner, guest } = setup();
        for (const user of [owner, guest]) {
            expect(fileNames(user)).toEqual([
                'img/a.png',
                'main.pdf',
                'notes.txt',
            ]);
            expect(
                user.mvs.settingsViewModelRepository.ephemeralFolders()
            ).toEqual(['empty']);
            expect(user.collabRepository.current.filesReady).toBe(true);
            expect(user.mvs.ideViewModelRepository.getFilesRequestState()).toBe(
                'ok'
            );
        }
    });

    test('a REST reload of the list keeps the session files and takes generated files', async () => {
        const { owner } = setup();
        owner.rpi.listFilesRequest = jest.fn().mockResolvedValue(
            ok({
                files: [
                    { ...GENERATED, fileName: 'out/main.log' },
                    // a stale user file of the REST list does not come back
                    { autogenerated: false, fileName: 'old.txt', url: 'x' },
                ],
            })
        );
        await owner.ctx.loaderService.loadFiles(PROJECT_ID);
        expect(fileNames(owner)).toEqual([
            'img/a.png',
            'notes.txt',
            'out/main.log',
        ]);
    });

    test('folders, files and renames of one participant reach the other', async () => {
        const { owner, guest, net, authority } = setup();

        // the guest of a public project changes files through the session
        guest.ctx.fileManagerService.onCreateFolder('docs', '');
        await settle(net);
        expect(
            owner.mvs.settingsViewModelRepository.ephemeralFolders()
        ).toEqual(['docs', 'empty']);

        await run(net, () => guest.ctx.fileManagerService.onCreateFile());
        await settle(net);
        expect(authority.filePaths()).toContain('new.txt');
        expect(fileNames(owner)).toContain('new.txt');
        // the new file is open for its author as a document
        expect(guest.mvs.ideViewModelRepository.activeTextFile()).toBe(
            'new.txt'
        );
        expect(guest.files.isBound('new.txt')).toBe(true);

        await run(net, () =>
            guest.ctx.fileManagerService.onFileNameChanged('notes.txt', 'n.txt')
        );
        await settle(net);
        expect(fileNames(owner)).toEqual([
            'img/a.png',
            'main.pdf',
            'n.txt',
            'new.txt',
        ]);
        // the author edits references in segments as document updates
        expect(authority.text(1)).toBe('see n.txt and img/a.png');
        expect(
            owner.ctx.programService.getCurrentProgram().segments[0].text
        ).toBe('see n.txt and img/a.png');

        await run(net, () =>
            owner.ctx.fileManagerService.onSvarMoveFiles(['/n.txt'], '/docs')
        );
        await settle(net);
        expect(fileNames(guest)).toContain('docs/n.txt');
        expect(
            guest.mvs.settingsViewModelRepository.ephemeralFolders()
        ).toEqual(['empty']);

        await run(net, () =>
            owner.ctx.fileManagerService.onRenameFolder('docs', 'papers')
        );
        await settle(net);
        expect(fileNames(guest)).toContain('papers/n.txt');

        await run(net, () =>
            guest.ctx.fileManagerService.onDeleteFolder('empty')
        );
        await run(net, () =>
            owner.ctx.fileManagerService.onDeleteFile('img/a.png')
        );
        await settle(net);
        expect(fileNames(guest)).toEqual([
            'main.pdf',
            'new.txt',
            'papers/n.txt',
        ]);
        expect(
            owner.mvs.settingsViewModelRepository.ephemeralFolders()
        ).toEqual([]);
        // no REST file endpoint was used by anybody
        for (const user of [owner, guest]) {
            expect(user.rpi.uploadFileRequest).not.toHaveBeenCalled();
            expect(user.rpi.renameFileRequest).not.toHaveBeenCalled();
            expect(user.rpi.deleteFileRequest).not.toHaveBeenCalled();
        }
    });

    test('the first of two renames of the same file wins, the second sees not found', async () => {
        for (const seed of [1, 2, 3, 4, 5]) {
            const { owner, guest, net, authority } = setup({}, seed);
            const a = owner.ctx.fileManagerService.onFileNameChanged(
                'notes.txt',
                'alice.txt'
            );
            const b = guest.ctx.fileManagerService.onFileNameChanged(
                'notes.txt',
                'bob.txt'
            );
            await settle(net);
            await Promise.all([a, b]);
            const paths = authority.filePaths();
            const winner = paths.includes('alice.txt') ? owner : guest;
            const loser = winner === owner ? guest : owner;
            expect(paths.filter((p) => p.endsWith('.txt'))).toHaveLength(1);
            expect(fileNames(owner)).toEqual(fileNames(guest));
            expect(
                loser.mvs.mockState().toasts.map((t) => t.message)
            ).toContain(loser.mvs.dictionary.filemanager.errors.notFound);
            expect(winner.mvs.mockState().toasts).toHaveLength(0);
        }
    });

    test('two participants creating a file at once get two names', async () => {
        for (const seed of [11, 12, 13]) {
            const { owner, guest, net, authority } = setup({}, seed);
            const a = owner.ctx.fileManagerService.onCreateFile();
            const b = guest.ctx.fileManagerService.onCreateFile();
            await settle(net);
            await Promise.all([a, b]);
            expect(authority.filePaths()).toEqual(
                expect.arrayContaining(['new.txt', 'new(1).txt'])
            );
            expect(owner.mvs.mockState().toasts).toHaveLength(0);
            expect(guest.mvs.mockState().toasts).toHaveLength(0);
            expect(
                [
                    owner.mvs.ideViewModelRepository.activeTextFile(),
                    guest.mvs.ideViewModelRepository.activeTextFile(),
                ].sort()
            ).toEqual(['new(1).txt', 'new.txt']);
        }
    });

    test('a rejected command shows the toast of the REST answer', async () => {
        const { owner, net } = setup();
        await run(net, () =>
            owner.ctx.fileManagerService.onFileNameChanged('notes.txt', 'img')
        );
        await settle(net);
        expect(owner.mvs.mockState().toasts.map((t) => t.message)).toEqual([
            owner.mvs.dictionary.filemanager.errors.fileAlreadyExists,
        ]);
    });

    test('two users edit a text file together and see each other', async () => {
        for (const seed of [21, 22, 23]) {
            const { owner, guest, net, authority } = setup({}, seed);
            await openTextFile(owner, net, 'notes.txt');
            await openTextFile(guest, net, 'notes.txt');
            for (const user of [owner, guest]) {
                expect(user.mvs.ideViewModelRepository.textFileContent()).toBe(
                    'hello\nworld'
                );
                expect(
                    user.mvs.ideViewModelRepository.loadTextFileRequestState()
                ).toBe('ok');
            }
            const ownerView = textEditorView(owner);
            const guestView = textEditorView(guest);
            ownerView.type(0, 'A');
            guestView.type(11, '!');
            ownerView.type(1, 'B');
            await settle(net);
            const expected = 'ABhello\nworld!';
            expect(authority.fileContent('notes.txt')).toBe(expected);
            for (const user of [owner, guest]) {
                expect(user.mvs.ideViewModelRepository.textFileContent()).toBe(
                    expected
                );
            }
            expect(ownerView.view.doc.toString()).toBe(expected);
            expect(guestView.view.doc.toString()).toBe(expected);
            // no autosave over REST while the file is a document
            await new Promise((resolve) => setTimeout(resolve, 1100));
            expect(owner.rpi.uploadFileRequest).not.toHaveBeenCalled();

            guestView.select(3);
            await new Promise((resolve) => setTimeout(resolve, 150));
            await settle(net);
            expect(ownerView.view.cursors).toEqual([
                expect.objectContaining({ displayName: 'bob', head: 3 }),
            ]);
        }
    });

    test('the open file follows a rename by somebody else and closes on delete', async () => {
        const { owner, guest, net } = setup();
        await openTextFile(guest, net, 'notes.txt');
        const guestView = textEditorView(guest);

        await run(net, () =>
            owner.ctx.fileManagerService.onRenameFolder('img', 'pics')
        );
        await run(net, () =>
            owner.ctx.fileManagerService.onFileNameChanged(
                'notes.txt',
                'renamed.txt'
            )
        );
        await settle(net);
        expect(guest.mvs.ideViewModelRepository.activeTextFile()).toBe(
            'renamed.txt'
        );
        expect(guest.files.isBound('renamed.txt')).toBe(true);
        // the guest's editor stays writable: the file is bound under its new path
        expect(guest.collabRepository.current.textFileDocPath).toBe(
            'renamed.txt'
        );
        // still the same document: edits go on
        guestView.type(0, '>');
        await settle(net);
        expect(net.authority.fileContent('renamed.txt')).toBe('>hello\nworld');

        await run(net, () =>
            owner.ctx.fileManagerService.onDeleteFile('renamed.txt')
        );
        await settle(net);
        expect(guest.mvs.ideViewModelRepository.activeTextFile()).toBeNull();
        expect(guest.files.bindingKey()).toBeUndefined();
        expect(guest.collabRepository.current.textFileDocPath).toBeNull();
    });

    test('an image follows a folder rename and gets a new revision on upload', async () => {
        const { owner, guest, net, authority } = setup();
        await guest.ctx.textFileEditorService.onImageFileOpened('img/a.png');
        expect(guest.mvs.ideViewModelRepository.activeImageFile()).toBe(
            'img/a.png'
        );
        await run(net, () =>
            owner.ctx.fileManagerService.onRenameFolder('img', 'pics')
        );
        await settle(net);
        expect(guest.mvs.ideViewModelRepository.activeImageFile()).toBe(
            'pics/a.png'
        );

        const uploaded = guest.ctx.fileManagerService.onUploadFiles(
            [new File(['a,b\n1,2'], 'data.csv', { type: 'text/csv' })],
            'pics'
        );
        await settle(net);
        expect(await uploaded).toEqual(['pics/data.csv']);
        expect(fileNames(owner)).toContain('pics/data.csv');
        expect(authority.fileContent('pics/data.csv')).toBe('a,b\n1,2');
        expect(guest.rpi.uploadCollabFileRequest).toHaveBeenCalledWith(
            expect.anything(),
            PROJECT_ID,
            'pics/data.csv',
            expect.stringMatching(/^bob-/)
        );

        authority.upload(
            owner.collabRepository.current.selfConnectionId!,
            'pics/a.png',
            'PNG-2'
        );
        await settle(net);
        expect(guest.collabRepository.current.fileRevisions['pics/a.png']).toBe(
            1
        );
    });

    test('an upload over an open text file reaches the editor as a server update', async () => {
        const { owner, guest, net, authority } = setup();
        await openTextFile(owner, net, 'notes.txt');
        const ownerView = textEditorView(owner);
        authority.upload(
            guest.collabRepository.current.selfConnectionId!,
            'notes.txt',
            'replaced'
        );
        await settle(net);
        expect(owner.mvs.ideViewModelRepository.textFileContent()).toBe(
            'replaced'
        );
        expect(ownerView.view.doc.toString()).toBe('replaced');
    });

    test('edits made while disconnected are pushed after the reconnect', async () => {
        const { owner, guest, net, authority } = setup();
        await openTextFile(owner, net, 'notes.txt');
        await openTextFile(guest, net, 'notes.txt');
        const ownerView = textEditorView(owner);
        const guestView = textEditorView(guest);

        guest.socket.drop();
        await settle(net);
        guestView.type(0, 'offline ');
        ownerView.type(11, ' online');
        // a rename while the guest is away: the document follows it after the reconnect
        await run(net, () =>
            owner.ctx.fileManagerService.onFileNameChanged(
                'notes.txt',
                'n2.txt'
            )
        );
        await settle(net);

        guest.socket.reconnect();
        await settle(net);
        const expected = 'offline hello\nworld online';
        expect(authority.fileContent('n2.txt')).toBe(expected);
        expect(guest.mvs.ideViewModelRepository.activeTextFile()).toBe(
            'n2.txt'
        );
        expect(guest.mvs.ideViewModelRepository.textFileContent()).toBe(
            expected
        );
        expect(owner.mvs.ideViewModelRepository.textFileContent()).toBe(
            expected
        );
    });

    test('a file deleted while disconnected closes the editor after the reconnect', async () => {
        const { owner, guest, net } = setup();
        await openTextFile(guest, net, 'notes.txt');
        guest.socket.drop();
        await settle(net);
        await run(net, () =>
            owner.ctx.fileManagerService.onDeleteFile('notes.txt')
        );
        await settle(net);
        guest.socket.reconnect();
        await settle(net);
        expect(guest.mvs.ideViewModelRepository.activeTextFile()).toBeNull();
        expect(fileNames(guest)).toEqual(['img/a.png', 'main.pdf']);
    });

    test('without file collaboration on the server the owner works over REST', async () => {
        const { owner, guest, net } = setup({ withoutFiles: true });
        expect(owner.collabRepository.current.filesReady).toBe(false);
        expect(fileNames(owner)).toEqual(['main.pdf']);
        await run(net, () =>
            owner.ctx.fileManagerService.onFileNameChanged('a.txt', 'b.txt')
        );
        await settle(net);
        expect(owner.rpi.renameFileRequest).toHaveBeenCalled();
        // a guest without a session list cannot change files
        await run(net, () => guest.ctx.fileManagerService.onCreateFile());
        expect(guest.rpi.uploadFileRequest).not.toHaveBeenCalled();
    });

    test('commands while the agent holds the project are refused with the lock notice', async () => {
        const { owner, net, authority } = setup();
        authority.setLocked(true);
        net.flush();
        await run(net, () =>
            owner.ctx.fileManagerService.onFileNameChanged('notes.txt', 'x.txt')
        );
        await settle(net);
        expect(authority.filePaths()).toContain('notes.txt');
        expect(owner.mvs.mockState().toasts.map((t) => t.message)).toEqual([
            owner.mvs.dictionary.agent_chat.editing_locked,
        ]);
    });
});
