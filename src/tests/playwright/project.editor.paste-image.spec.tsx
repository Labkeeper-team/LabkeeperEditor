/** Файлы проекта как на сервере: загрузка кладёт, удаление убирает, хранилище отдаёт с долгим кэшем */
async function setupFileStore(page: Page) {
    const files = new Map<string, Buffer>();
    const uploads: string[] = [];
    await page.route(
        (url) => url.pathname === `${FILES_API}/upload`,
        async (route) => {
            const name = new URL(route.request().url()).searchParams.get(
                'name'
            )!;
            const raw = route.request().postDataBuffer() ?? Buffer.alloc(0);
            // тело файла между заголовками части и завершающей границей
            const start = raw.indexOf('\r\n\r\n') + 4;
            const end = raw.lastIndexOf('\r\n--');
            files.set(name, raw.subarray(start, end));
            uploads.push(name);
            await route.fulfill({
                status: 201,
                contentType: 'application/json',
                body: JSON.stringify(`${STORAGE}${name}`),
            });
        }
    );
    await page.route(
        (url) => url.pathname === `${FILES_API}/delete`,
        async (route) => {
            files.delete(
                new URL(route.request().url()).searchParams.get('name')!
            );
            await route.fulfill({ status: 200 });
        }
    );
    await page.route(
        (url) => url.pathname === `${FILES_API}/list`,
        async (route) => {
            await route.fulfill({
                status: 200,
                contentType: 'application/json',
                body: JSON.stringify({
                    files: [...files.keys()].map((fileName) => ({
                        fileName,
                        autogenerated: false,
                        url: `${STORAGE}${fileName}`,
                    })),
                }),
            });
        }
    );
    await page.route(`${STORAGE}**`, async (route) => {
        const name = route.request().url().slice(STORAGE.length);
        const body = files.get(name);
        await route.fulfill(
            body
                ? {
                      status: 200,
                      contentType: 'image/png',
                      headers: { 'Cache-Control': 'max-age=3600' },
                      body,
                  }
                : { status: 404 }
        );
    });
    return { uploads };
}

async function pasteImage(page: Page, base64: string) {
    const editor = page.locator('#ide-segment-0 .cm-content');
    await editor.click();
    await page.keyboard.press('ControlOrMeta+End');
    await editor.evaluate((element, data) => {
        const bytes = Uint8Array.from(atob(data), (char) => char.charCodeAt(0));
        const clipboardData = new DataTransfer();
        clipboardData.items.add(
            new File([bytes], 'image.png', { type: 'image/png' })
        );
        element.dispatchEvent(
            new ClipboardEvent('paste', {
                clipboardData,
                bubbles: true,
                cancelable: true,
            })
        );
    }, base64);
}

const resultPicture = (page: Page) => page.locator('#compile-result img');

// GH-173: новая картинка получала имя удалённой, ссылка в тексте сегмента
// оставалась прежней, и на странице висела старая картинка из кэша
test('pasted-image-after-a-deleted-one-shows-the-new-picture', async ({
    page,
}) => {
    const routeSetup = new RouteSetup(page);
    await routeSetup.setupGetUserInfoRequest(true);
    await routeSetup.setupGetProjectRequest(200, 'default', {
        segments: [
            { id: 1, type: 'md', text: 'Photo', parameters: { visible: true } },
        ],
        parameters: { roundStrategy: 'noRound' },
    });
    await routeSetup.setupGetAllProjectsRequest();
    await routeSetup.setupSaveProgramRequest();
    const store = await setupFileStore(page);

    await page.goto(`/project/${uuid}`);
    await expect(page.locator('#ide-segment-0 .cm-content')).toBeVisible({
        timeout: 15_000,
    });

    await pasteImage(page, RED_4PX);
    await expect(resultPicture(page)).toHaveJSProperty('naturalWidth', 4);
    const firstSrc = await resultPicture(page).getAttribute('src');

    // убираем картинку из текста и соглашаемся удалить её файл
    const editor = page.locator('#ide-segment-0 .cm-content');
    await editor.click();
    await page.keyboard.press('ControlOrMeta+a');
    await page.keyboard.press('Backspace');
    await page.getByRole('button', { name: 'Yes' }).click();
    await expect(resultPicture(page)).toHaveCount(0);

    await pasteImage(page, BLUE_8PX);
    await expect(resultPicture(page)).toHaveJSProperty('naturalWidth', 8);
    expect(await resultPicture(page).getAttribute('src')).not.toBe(firstSrc);
    expect(new Set(store.uploads).size).toBe(2);
});
